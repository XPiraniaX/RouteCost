CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_notification_id BIGINT NOT NULL REFERENCES reminder_notifications (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    reminder_id BIGINT NOT NULL REFERENCES reminders (id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    message VARCHAR(300) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT uq_user_notification_source UNIQUE (reminder_notification_id)
);

CREATE INDEX idx_user_notifications_owner_created ON user_notifications (user_id, created_at DESC, id DESC);
CREATE INDEX idx_user_notifications_unread ON user_notifications (user_id, created_at DESC, id DESC) WHERE read_at IS NULL;
