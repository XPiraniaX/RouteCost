CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    production_year INTEGER NOT NULL,
    fuel_type VARCHAR(20) NOT NULL,
    current_odometer INTEGER NOT NULL DEFAULT 0,
    purchase_date DATE NOT NULL,
    purchase_price NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_vehicles_production_year CHECK (production_year BETWEEN 1886 AND 2100),
    CONSTRAINT chk_vehicles_fuel_type CHECK (fuel_type IN ('PETROL', 'DIESEL', 'LPG', 'HYBRID', 'ELECTRIC', 'OTHER')),
    CONSTRAINT chk_vehicles_odometer CHECK (current_odometer >= 0),
    CONSTRAINT chk_vehicles_purchase_price CHECK (purchase_price >= 0)
);

CREATE INDEX idx_vehicles_owner_id ON vehicles (owner_id);
CREATE INDEX idx_vehicles_owner_created_at ON vehicles (owner_id, created_at DESC);
