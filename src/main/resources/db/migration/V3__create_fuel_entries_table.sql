CREATE TABLE fuel_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    entry_date DATE NOT NULL,
    odometer INTEGER NOT NULL,
    liters NUMERIC(10, 3) NOT NULL,
    total_cost NUMERIC(12, 2) NOT NULL,
    full_tank BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_fuel_entries_odometer CHECK (odometer >= 0),
    CONSTRAINT chk_fuel_entries_liters CHECK (liters > 0),
    CONSTRAINT chk_fuel_entries_total_cost CHECK (total_cost > 0)
);

CREATE INDEX idx_fuel_entries_vehicle_date_id ON fuel_entries (vehicle_id, entry_date, id);
