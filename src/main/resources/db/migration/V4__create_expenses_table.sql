CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    expense_date DATE NOT NULL,
    category VARCHAR(30) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    currency CHAR(3) NOT NULL,
    description VARCHAR(1000),
    odometer INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_expenses_category CHECK (
        category IN ('REPAIR', 'PARTS', 'SERVICE', 'INSURANCE', 'TECHNICAL_INSPECTION', 'TIRES', 'CAR_WASH', 'OTHER')
    ),
    CONSTRAINT chk_expenses_amount CHECK (amount > 0),
    CONSTRAINT chk_expenses_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_expenses_odometer CHECK (odometer IS NULL OR odometer >= 0)
);

CREATE INDEX idx_expenses_vehicle_date_id ON expenses (vehicle_id, expense_date DESC, id DESC);
CREATE INDEX idx_expenses_vehicle_category_date ON expenses (vehicle_id, category, expense_date);
