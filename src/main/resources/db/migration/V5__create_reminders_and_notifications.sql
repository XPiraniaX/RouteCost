CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    odometer INTEGER,
    activation_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_reminders_type CHECK (
        type IN ('INSURANCE', 'TECHNICAL_INSPECTION', 'SERVICE', 'OIL_CHANGE', 'TIRES', 'OTHER')
    ),
    CONSTRAINT chk_reminders_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_reminders_odometer CHECK (odometer IS NULL OR odometer >= 0),
    CONSTRAINT chk_reminders_activation_version CHECK (activation_version > 0)
);

CREATE INDEX idx_reminders_vehicle_due_status ON reminders (vehicle_id, due_date, status);
CREATE INDEX idx_reminders_status_due_date ON reminders (status, due_date);

CREATE TABLE reminder_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id BIGINT NOT NULL REFERENCES reminders (id) ON DELETE CASCADE,
    activation_version INTEGER NOT NULL,
    notification_kind VARCHAR(20) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE,
    processed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT uq_reminder_notification_generation UNIQUE (
        reminder_id, activation_version, notification_kind, due_date
    ),
    CONSTRAINT chk_reminder_notification_kind CHECK (notification_kind IN ('UPCOMING', 'OVERDUE')),
    CONSTRAINT chk_reminder_notification_status CHECK (
        status IN ('PENDING', 'PUBLISHED', 'PROCESSED', 'DISCARDED')
    ),
    CONSTRAINT chk_reminder_notification_activation CHECK (activation_version > 0)
);

CREATE INDEX idx_reminder_notifications_pending ON reminder_notifications (status, created_at, id);
